// Builds css/tw.css: the Tailwind utilities every page uses, compiled once instead of in each visitor's browser.
// Run after changing classes in any .html / .js file:
//   npm i -D tailwindcss@4 esbuild      (once; esbuild only minifies)
//   node scripts/build-css.mjs
// It scans every .html and .js file for class names (including ones built in JS strings) and writes css/tw.css.
import { compile } from 'tailwindcss';
import { createRequire } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TW = path.dirname(createRequire(import.meta.url).resolve('tailwindcss/package.json'));
const SKIP = new Set(['.git', 'node_modules', 'worker', 'functions', 'scripts']);

const files = [];
(function walk(d) {
  for (const f of fs.readdirSync(d)) {
    if (SKIP.has(f)) continue;
    const p = path.join(d, f);
    if (fs.statSync(p).isDirectory()) walk(p); else if (/\.(html|js)$/.test(f)) files.push(p);
  }
})(ROOT);
const candidates = new Set();
for (const f of files) for (const m of fs.readFileSync(f, 'utf8').matchAll(/[^\s"'`<>=]+/g)) candidates.add(m[0].replace(/^[({]+|[),;}]+$/g, ''));

// Same design tokens as the old Play CDN config (js/tw-config.js).
const input = `@import "tailwindcss";
@custom-variant dark (&:where(.dark, .dark *));
@theme {
  --color-gallery: #ffffff; --color-mist: #f5f5f7; --color-frost: #fafafc; --color-hairline: #d6d6d6; --color-control: #e6e6e8;
  --color-ink: #1d1d1f; --color-slate: #6e6e73; --color-steel: #86868b; --color-appleBlue: #0066cc; --color-pricingBlue: #0071e3;
  --color-launchOrange: #b64400; --color-cyanGlow: #00e5ff; --color-brandNavy: #0b1f6b; --color-brandTeal: #159a9c;
  --font-heading: -apple-system, BlinkMacSystemFont, 'SF Pro Display', Inter, Prompt, sans-serif;
  --font-display: -apple-system, BlinkMacSystemFont, 'SF Pro Display', Inter, Prompt, sans-serif;
  --font-body: -apple-system, BlinkMacSystemFont, 'SF Pro Text', Inter, Prompt, sans-serif;
  --font-mono: 'SF Mono', ui-monospace, Menlo, monospace;
  --radius-card: 28px; --radius-links: 10px; --radius-pill: 36px; --radius-images: 28px; --radius-input: 980px; --radius-button: 9999px; --radius-nav: 20px;
}
/* Tailwind 3 defaults the pages were written against */
@layer base {
  *, ::after, ::before, ::backdrop, ::file-selector-button { border-color: #e5e7eb; }
  input::placeholder, textarea::placeholder { color: #9ca3af; }
  button:not(:disabled), [role="button"]:not(:disabled) { cursor: pointer; }
}`;
const compiler = await compile(input, {
  base: TW,
  loadStylesheet: async (id, base) => {
    const file = id === 'tailwindcss' ? path.join(TW, 'index.css') : id.startsWith('tailwindcss/') ? path.join(TW, id.slice(12)) : path.resolve(base, id);
    return { path: file, base: path.dirname(file), content: fs.readFileSync(file, 'utf8') };
  }
});
let css = compiler.build([...candidates]);
try { css = (await (await import('esbuild')).transform(css, { loader: 'css', minify: true })).code; } // optional: npm i -D esbuild
catch { css = css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\n\s*\n/g, '\n'); }
const out = path.join(ROOT, 'css', 'tw.css');
fs.writeFileSync(out, `/* Generated by scripts/build-css.mjs — do not edit by hand. */\n${css}`);
console.log(`css/tw.css ${(fs.statSync(out).size / 1024).toFixed(1)} KB from ${files.length} files`);
